import AppKit
import Foundation
import Observation
import UniformTypeIdentifiers

enum ClipboardContentType: String, Codable, Sendable {
    case text
    case url
    case image
    case file
}

struct ClipboardItem: Identifiable, Codable, Equatable, Sendable {
    let id: UUID
    var timestamp: Date
    let type: ClipboardContentType
    var textValue: String?
    var urlString: String?
    var filePaths: [String]?
    var imageFileName: String?
    var previewTitle: String
    var previewSubtitle: String?
    var byteCount: Int?
    var imageDimensions: String?

    var contentSignature: String {
        switch type {
        case .text:
            return "text:" + (textValue ?? "")
        case .url:
            return "url:" + (urlString ?? "")
        case .file:
            return "file:" + (filePaths?.sorted().joined(separator: "|") ?? "")
        case .image:
            return "image:" + previewTitle + "_\(byteCount ?? 0)"
        }
    }
}

@MainActor @Observable
final class ClipboardManager {
    private(set) var items: [ClipboardItem] = []
    private(set) var isEnabled: Bool
    private(set) var shortcutConflictError: String?

    @ObservationIgnored private let settings: SettingsManager
    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let storageDirectory: URL
    @ObservationIgnored private let imagesDirectory: URL
    @ObservationIgnored private let historyFileURL: URL
    @ObservationIgnored private var timer: DispatchSourceTimer?
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var isRestoring = false
    @ObservationIgnored private let hotKey: ClipboardHotKey
    @ObservationIgnored var onOpenPanel: ((NSRunningApplication?) -> Void)?

    /// Pasteboard types that indicate concealed/transient content (e.g. password managers).
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    init(settings: SettingsManager,
         storageDirectory: URL? = nil,
         pasteboard: NSPasteboard = .general) {
        self.settings = settings
        self.pasteboard = pasteboard
        self.isEnabled = settings.preferences.clipboardHistoryEnabled
        self.lastChangeCount = pasteboard.changeCount

        let baseDir = storageDirectory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
            .appendingPathComponent("PulseBar/Clipboard", isDirectory: true)
        self.storageDirectory = baseDir
        self.imagesDirectory = baseDir.appendingPathComponent("Images", isDirectory: true)
        self.historyFileURL = baseDir.appendingPathComponent("history.json")

        self.hotKey = ClipboardHotKey()

        createDirectoriesIfNeeded()
        loadFromDisk()

        self.hotKey.onTriggerWithApp = { [weak self] app in
            self?.openPanel(targetApp: app)
        }

        if isEnabled {
            startMonitoring()
            registerShortcut()
        }
    }

    private func createDirectoriesIfNeeded() {
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
    }

    func setEnabled(_ enabled: Bool) {
        guard enabled != isEnabled else { return }
        isEnabled = enabled
        settings.update { $0.clipboardHistoryEnabled = enabled }
        if enabled {
            startMonitoring()
            registerShortcut()
        } else {
            stopMonitoring()
            unregisterShortcut()
        }
    }

    private func registerShortcut() {
        hotKey.register()
        shortcutConflictError = hotKey.conflictError
    }

    private func unregisterShortcut() {
        hotKey.unregister()
        shortcutConflictError = nil
    }

    func openPanel(targetApp: NSRunningApplication? = nil) {
        onOpenPanel?(targetApp)
    }

    func startMonitoring() {
        guard isEnabled else { return }
        stopMonitoring()
        lastChangeCount = pasteboard.changeCount

        let source = DispatchSource.makeTimerSource(queue: .main)
        source.schedule(deadline: .now() + .milliseconds(500), repeating: .milliseconds(500), leeway: .milliseconds(50))
        source.setEventHandler { [weak self] in
            self?.pollPasteboard()
        }
        self.timer = source
        source.resume()
    }

    func stopMonitoring() {
        timer?.cancel()
        timer = nil
    }

    func sleep() {
        stopMonitoring()
        unregisterShortcut()
    }

    func wake() {
        if isEnabled {
            startMonitoring()
            registerShortcut()
        }
    }

    func shutdown() {
        stopMonitoring()
        unregisterShortcut()
    }

    func pollPasteboard() {
        guard isEnabled else { return }
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        guard !isRestoring else { return }

        // Skip concealed/transient types (e.g. password managers)
        if let types = pasteboard.types, types.contains(where: { Self.concealedTypes.contains($0) }) {
            return
        }

        captureCurrentPasteboard()
    }

    private func captureCurrentPasteboard() {
        // 1. Check file URLs first
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            if let item = makeFileItem(urls: urls) {
                addItem(item)
                return
            }
        }

        // 2. Check web URLs
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           let url = urls.first, !url.isFileURL,
           let scheme = url.scheme?.lowercased(), ["http", "https", "ftp"].contains(scheme) {
            let item = makeURLItem(url: url)
            addItem(item)
            return
        }

        // 3. Check image data
        let imageTypes = [NSPasteboard.PasteboardType.png, .tiff,
                          NSPasteboard.PasteboardType("public.png"),
                          NSPasteboard.PasteboardType("public.tiff")]
        if let types = pasteboard.types, types.contains(where: { imageTypes.contains($0) }),
           let image = NSImage(pasteboard: pasteboard) {
            if let item = makeImageItem(image: image) {
                addItem(item)
                return
            }
        }

        // 4. Check plain text
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if let url = URL(string: trimmed),
               let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme),
               url.host != nil {
                let item = makeURLItem(url: url)
                addItem(item)
            } else {
                let item = makeTextItem(text: text)
                addItem(item)
            }
            return
        }
    }

    private func makeFileItem(urls: [URL]) -> ClipboardItem? {
        let validURLs = urls.filter { FileManager.default.fileExists(atPath: $0.path) }
        guard !validURLs.isEmpty else { return nil }
        let paths = validURLs.map(\.path)
        let names = validURLs.map(\.lastPathComponent)
        let title: String
        let subtitle: String?
        if validURLs.count == 1 {
            title = names[0]
            subtitle = validURLs[0].deletingLastPathComponent().path
        } else {
            title = "\(validURLs.count) files"
            subtitle = names.prefix(3).joined(separator: ", ") + (names.count > 3 ? "..." : "")
        }
        return ClipboardItem(
            id: UUID(),
            timestamp: Date(),
            type: .file,
            textValue: paths.joined(separator: "\n"),
            urlString: nil,
            filePaths: paths,
            imageFileName: nil,
            previewTitle: title,
            previewSubtitle: subtitle,
            byteCount: nil,
            imageDimensions: nil
        )
    }

    private func makeURLItem(url: URL) -> ClipboardItem {
        let urlString = url.absoluteString
        let title = url.host ?? urlString
        let subtitle = urlString
        return ClipboardItem(
            id: UUID(),
            timestamp: Date(),
            type: .url,
            textValue: urlString,
            urlString: urlString,
            filePaths: nil,
            imageFileName: nil,
            previewTitle: title,
            previewSubtitle: subtitle,
            byteCount: urlString.utf8.count,
            imageDimensions: nil
        )
    }

    private func makeImageItem(image: NSImage) -> ClipboardItem? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let pngData = rep.representation(using: .png, properties: [:]) else {
            return nil
        }
        createDirectoriesIfNeeded()
        let id = UUID()
        let fileName = "\(id.uuidString).png"
        let fileURL = imagesDirectory.appendingPathComponent(fileName)
        do {
            try pngData.write(to: fileURL, options: .atomic)
        } catch {
            return nil
        }
        let width = Int(rep.pixelsWide)
        let height = Int(rep.pixelsHigh)
        let dimensions = "\(width) × \(height)"
        let title = "Image (\(dimensions))"
        let subtitle = ByteCountFormatter.string(fromByteCount: Int64(pngData.count), countStyle: .file)
        return ClipboardItem(
            id: id,
            timestamp: Date(),
            type: .image,
            textValue: nil,
            urlString: nil,
            filePaths: nil,
            imageFileName: fileName,
            previewTitle: title,
            previewSubtitle: subtitle,
            byteCount: pngData.count,
            imageDimensions: dimensions
        )
    }

    private func makeTextItem(text: String) -> ClipboardItem {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let firstLine = trimmed.components(separatedBy: .newlines).first(where: { !$0.trimmingCharacters(in: .whitespaces).isEmpty }) ?? trimmed
        let title = String(firstLine.prefix(80))
        let charCount = text.count
        let lineCount = text.components(separatedBy: .newlines).count
        let subtitle = "\(charCount) char\(charCount == 1 ? "" : "s")\(lineCount > 1 ? " \u{2022} \(lineCount) lines" : "")"
        return ClipboardItem(
            id: UUID(),
            timestamp: Date(),
            type: .text,
            textValue: text,
            urlString: nil,
            filePaths: nil,
            imageFileName: nil,
            previewTitle: title,
            previewSubtitle: subtitle,
            byteCount: text.utf8.count,
            imageDimensions: nil
        )
    }

    func addItem(_ item: ClipboardItem) {
        // Deduplication: if an item with identical content already exists, bring it to the top
        if let existingIndex = items.firstIndex(where: { $0.contentSignature == item.contentSignature }) {
            var existing = items.remove(at: existingIndex)
            existing.timestamp = Date()
            // If the incoming item created a duplicate image file, clean it up
            if item.type == .image, let newFileName = item.imageFileName, newFileName != existing.imageFileName {
                let newURL = imagesDirectory.appendingPathComponent(newFileName)
                try? FileManager.default.removeItem(at: newURL)
            }
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        pruneToLimit()
        saveToDisk()
    }

    func pruneToLimit() {
        let limit = settings.preferences.clipboardLimit
        if items.count > limit {
            let excess = items.suffix(from: limit)
            for item in excess {
                if let fileName = item.imageFileName {
                    let fileURL = imagesDirectory.appendingPathComponent(fileName)
                    try? FileManager.default.removeItem(at: fileURL)
                }
            }
            items.removeSubrange(limit..<items.count)
        }
    }

    func restore(_ item: ClipboardItem) {
        isRestoring = true
        pasteboard.clearContents()

        switch item.type {
        case .text:
            if let text = item.textValue {
                pasteboard.setString(text, forType: .string)
            }
        case .url:
            if let urlString = item.urlString, let url = URL(string: urlString) {
                pasteboard.setString(urlString, forType: .string)
                pasteboard.writeObjects([url as NSURL])
            } else if let text = item.textValue {
                pasteboard.setString(text, forType: .string)
            }
        case .file:
            if let paths = item.filePaths {
                let urls = paths.map { URL(fileURLWithPath: $0) }
                pasteboard.writeObjects(urls as [NSURL])
            }
        case .image:
            if let fileName = item.imageFileName {
                let fileURL = imagesDirectory.appendingPathComponent(fileName)
                if let image = NSImage(contentsOf: fileURL) {
                    pasteboard.writeObjects([image])
                }
            }
        }

        // Delay resetting isRestoring and sync lastChangeCount
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { [weak self] in
            guard let self = self else { return }
            self.lastChangeCount = self.pasteboard.changeCount
            self.isRestoring = false
        }
    }

    func deleteItem(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        let removed = items.remove(at: index)
        if let fileName = removed.imageFileName {
            let fileURL = imagesDirectory.appendingPathComponent(fileName)
            try? FileManager.default.removeItem(at: fileURL)
        }
        saveToDisk()
    }

    func clearAll() {
        for item in items {
            if let fileName = item.imageFileName {
                let fileURL = imagesDirectory.appendingPathComponent(fileName)
                try? FileManager.default.removeItem(at: fileURL)
            }
        }
        items.removeAll()
        saveToDisk()
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        guard let fileName = item.imageFileName else { return nil }
        return imagesDirectory.appendingPathComponent(fileName)
    }

    private func saveToDisk() {
        createDirectoriesIfNeeded()
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyFileURL, options: .atomic)
    }

    private func loadFromDisk() {
        guard let data = try? Data(contentsOf: historyFileURL),
              let loaded = try? JSONDecoder().decode([ClipboardItem].self, from: data) else {
            return
        }
        items = loaded
        pruneToLimit()
    }
}
